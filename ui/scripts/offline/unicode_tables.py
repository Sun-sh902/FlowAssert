#!/usr/bin/env python3
"""Write ui/src/offline/unicodeTables.ts: the Unicode facts the browser check needs to behave as Python does.

    /usr/local/bin/python3 ui/scripts/offline/unicode_tables.py

The tables come from the running interpreter, so they follow its Unicode version. Regenerate with the Python
version the parity tests use, and commit the result; nothing generates them at build or test time.

  casefold     str.casefold, for the casefold rule
  case sets    which characters a literal matches under re.IGNORECASE (date formats are compiled that way)
  printable    str.isprintable, for repr() in the summary and the HTML report
  whitespace   str.isspace, for str.strip() and the regular expression \\s
  decimal      the decimal digits that re's \\d matches and int() reads, as the first code point of each run of ten
"""
import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[3] / "ui/src/offline/unicodeTables.ts"
CODE_POINTS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def js(text):
    """A TypeScript string literal with only ASCII characters."""
    out = []
    for ch in text:
        c = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append("\\u%04x" % c)
        else:
            out.append("\\u{%x}" % c)
    return '"' + "".join(out) + '"'


def ranges(points):
    result = []
    for c in points:
        if result and result[-1][1] == c - 1:
            result[-1][1] = c
        else:
            result.append([c, c])
    return result


def main():
    casefold = [(c, chr(c).casefold()) for c in CODE_POINTS if chr(c).casefold() != chr(c)]

    # Every character a literal matches under re.IGNORECASE, found with re itself.
    everything = "".join(chr(c) for c in CODE_POINTS)
    sets = {}
    for c in CODE_POINTS:
        ch = chr(c)
        if ch.lower() == ch and ch.upper() == ch and ch.casefold() == ch and ch.swapcase() == ch:
            # Cheap pre-filter; uncased characters are checked below.
            continue
        found = "".join(sorted(set(re.findall(re.escape(ch), everything, re.IGNORECASE))))
        if found != ch:
            sets[ch] = found
    # The pre-filter must not have skipped a character that matches anything else.
    for c in range(0, 0x110000, 997):
        ch = chr(c) if not 0xD800 <= c <= 0xDFFF else "a"
        if ch not in sets:
            assert re.findall(re.escape(ch), everything, re.IGNORECASE) == [ch] * everything.count(ch), hex(c)
    groups = sorted(set(sets.values()))
    for ch, group in sets.items():
        # The groups partition the cased characters: matching is symmetric and transitive here.
        assert all(sets.get(other, other) == group for other in group), hex(ord(ch))

    printable = ranges([c for c in CODE_POINTS if not chr(c).isprintable()])
    whitespace = "".join(chr(c) for c in CODE_POINTS if chr(c).isspace())
    zeros = [c for c in CODE_POINTS if unicodedata.decimal(chr(c), None) == 0]
    for c in CODE_POINTS:
        value = unicodedata.decimal(chr(c), None)
        if value is not None:
            assert any(z <= c <= z + 9 and c - z == value for z in zeros), hex(c)
    assert re.findall(r"\d", everything) == [chr(z + i) for z in zeros for i in range(10)]
    assert re.findall(r"\s", everything) == list(whitespace)

    lines = [
        "/**",
        " * Generated by ui/scripts/offline/unicode_tables.py. Do not edit.",
        f" * Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        " */",
        "",
        "/** str.casefold for every character it changes: character, then its folding. */",
        "export const CASEFOLD: readonly (readonly [number, string])[] = [",
    ]
    lines += [f"  [0x{c:x}, {js(f)}]," for c, f in casefold]
    lines += [
        "];",
        "",
        "/** Under re.IGNORECASE, a literal character matches every character of the group that holds it. */",
        "export const CASE_GROUPS: readonly string[] = [",
    ]
    lines += [f"  {js(g)}," for g in groups]
    lines += [
        "];",
        "",
        "/** Code point ranges, inclusive, for which str.isprintable is false (surrogates excluded). */",
        "export const NOT_PRINTABLE: readonly (readonly [number, number])[] = [",
    ]
    lines += [f"  [0x{a:x}, 0x{b:x}]," for a, b in printable]
    lines += [
        "];",
        "",
        "/** Every character for which str.isspace is true. */",
        f"export const WHITESPACE = {js(whitespace)};",
        "",
        "/** The digit zero of each run of ten decimal digits (Unicode category Nd). */",
        "export const DECIMAL_ZEROS: readonly number[] = [",
    ]
    lines += ["  " + ", ".join(f"0x{z:x}" for z in zeros[i:i + 8]) + "," for i in range(0, len(zeros), 8)]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(casefold)} foldings, {len(groups)} case groups, {len(printable)} ranges, {len(zeros)} digit runs")


if __name__ == "__main__":
    main()
